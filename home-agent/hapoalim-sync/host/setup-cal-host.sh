#!/bin/bash
# One-time NUC setup for the Cal (visaCal) card sync. Run by BEN, as root (sudo), after he approved the deploy and
# after hapoalim-sync's setup-host.sh exists on this host (shared runner dir + OTP inbox). Idempotent. Creates no
# secret (that is cal-setup) and never talks to Cal. Builds its OWN pinned image (CAL_SYNC_IMAGE), so the Hapoalim
# unit keeps the image it already runs.
set -euo pipefail
[ "$(id -u)" = 0 ] || { echo "run with sudo" >&2; exit 1; }
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
TAG=smarthome-hapoalim-sync:6.9.0-cal1
OUT_DIR="${CAL_OUT_DIR:-/home/ben/smarthome/data/cal/out}"
DATA_DIR="${CAL_DATA_DIR:-$(dirname -- "$OUT_DIR")}"
ARCHIVE_DIR="${CAL_ARCHIVE_DIR:-$DATA_DIR/archive}"
INBOX_DB="${CAL_INBOX_DB:-/home/ben/smarthome/home-agent/hermes/otp/codes.sqlite}"
INBOX_DIR=$(dirname -- "$INBOX_DB")
BEN_UID=$(id -u ben)
BEN_GID=$(id -g ben)
[ -f /usr/local/lib/hapoalim/hapoalim-runner.py ] || { echo "run hapoalim-sync/host/setup-host.sh first" >&2; exit 1; }
# cal-runner.py imports the installed hapoalim-runner.py, which imports the installed archive.py: only proceed when
# the deployed Hapoalim archive code IS this checkout's (fix3 deployed), so refreshing the runner cannot break it.
cmp -s "$HERE/archive.py" /usr/local/lib/hapoalim/archive.py \
  || { echo "installed /usr/local/lib/hapoalim/archive.py differs from this checkout: deploy fix3 (setup-host.sh) first" >&2; exit 1; }

install -d -m 0700 -o root -g root /var/lib/cal /var/lib/cal-spool
install -d -m 0700 -o "$BEN_UID" -g "$BEN_GID" "$DATA_DIR" "$OUT_DIR" "$ARCHIVE_DIR"

# Root-owned copies (an edit in the checkout does not change what root runs). hapoalim-runner.py, otp_take.py and
# otp_inbox.py are refreshed too: cal-runner.py subclasses the runner hooks and needs the `cal` OTP site.
install -d -m 0755 -o root -g root /usr/local/lib/hapoalim /etc/cal
install -m 0755 -o root -g root "$HERE/hapoalim-runner.py" /usr/local/lib/hapoalim/hapoalim-runner.py
install -m 0755 -o root -g root "$HERE/cal-runner.py" /usr/local/lib/hapoalim/cal-runner.py
install -m 0644 -o root -g root "$HERE/cal_archive.py" /usr/local/lib/hapoalim/cal_archive.py
install -m 0755 -o root -g root "$HERE/otp_take.py" /usr/local/lib/hapoalim/otp_take.py
install -m 0644 -o root -g root "$HERE/otp_inbox.py" /usr/local/lib/hapoalim/otp_inbox.py
install -m 0755 -o root -g root "$HERE/cal-setup" /usr/local/sbin/cal-setup

docker build --pull -t "$TAG" "$HERE/.."
image_id=$(docker image inspect --format '{{.Id}}' "$TAG")
docker run --rm --network none --entrypoint node "$image_id" -e \
  "const fs=require('fs');const c=fs.readFileSync('/app/node_modules/israeli-bank-scrapers/lib/scrapers/visa-cal.js','utf8');const h=fs.readFileSync('/app/node_modules/israeli-bank-scrapers/lib/scrapers/hapoalim.js','utf8');if(!c.includes('calWalkCardData')||!h.includes('hapoalimWalkTransactions')||!fs.existsSync('/app/cal-auto.mjs'))process.exit(3)" \
  || { echo "image is NOT patched for Cal" >&2; exit 1; }
printf 'CAL_SYNC_IMAGE=%s\n' "$image_id" >/etc/cal/image.env
chmod 0644 /etc/cal/image.env

install -m 0644 "$HERE/cal-run.service" "$HERE/cal-run.path" /etc/systemd/system/
install -d -m 0755 /etc/systemd/system/cal-run.service.d
cat > /etc/systemd/system/cal-run.service.d/paths.conf <<PATHS_EOF
# Generated by setup-cal-host.sh — do not edit by hand; re-run setup-cal-host.sh after changing paths.
[Service]
ReadWritePaths=$DATA_DIR $INBOX_DIR
PATHS_EOF
chmod 0644 /etc/systemd/system/cal-run.service.d/paths.conf
systemctl daemon-reload
systemctl enable --now cal-run.path
echo "OK. Next: sudo cal-setup  (type the Cal username + password), then (as ben):"
echo "  cd ~/smarthome/home-agent && docker compose up -d --build command-center command-center-mcp && docker compose restart hermes"
echo "Daily limit: CAL_MAX_RUNS_PER_DAY=2 in the unit; override in /etc/systemd/system/cal-run.service.d/limits.conf."
