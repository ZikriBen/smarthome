#!/bin/bash
# One-time NUC setup for Bank Hapoalim sync. Run by BEN, as root (sudo), only after he approved the deploy.
# Idempotent. Creates no secret (that is hapoalim-setup) and never talks to the bank.
set -euo pipefail
[ "$(id -u)" = 0 ] || { echo "run with sudo" >&2; exit 1; }
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
TAG=smarthome-hapoalim-sync:6.9.0-auto1
OUT_DIR="${HAPOALIM_OUT_DIR:-/home/ben/smarthome/data/hapoalim/out}"
DATA_DIR="${HAPOALIM_DATA_DIR:-$(dirname -- "$OUT_DIR")}"
ARCHIVE_DIR="${HAPOALIM_ARCHIVE_DIR:-$DATA_DIR/archive}"
INBOX_DB="${HAPOALIM_INBOX_DB:-/home/ben/smarthome/home-agent/hermes/otp/codes.sqlite}"
INBOX_DIR=$(dirname -- "$INBOX_DB")
BEN_UID=$(id -u ben)
BEN_GID=$(id -g ben)

# Data dirs: state/spool root-only; data/hapoalim (out + archive) owned by Ben.
install -d -m 0700 -o root -g root /var/lib/hapoalim /var/lib/hapoalim-spool
install -d -m 0700 -o "$BEN_UID" -g "$BEN_GID" "$DATA_DIR" "$OUT_DIR" "$ARCHIVE_DIR"

# Root runner must not be editable by ben/agents: copy it root-owned out of the repo.
install -d -m 0755 -o root -g root /usr/local/lib/hapoalim /etc/hapoalim
install -m 0755 -o root -g root "$HERE/hapoalim-runner.py" /usr/local/lib/hapoalim/hapoalim-runner.py
install -m 0644 -o root -g root "$HERE/archive.py" /usr/local/lib/hapoalim/archive.py
install -m 0755 -o root -g root "$HERE/otp_take.py" /usr/local/lib/hapoalim/otp_take.py
install -m 0644 -o root -g root "$HERE/otp_inbox.py" /usr/local/lib/hapoalim/otp_inbox.py
install -m 0755 -o root -g root "$HERE/hapoalim-setup" /usr/local/sbin/hapoalim-setup
install -m 0755 -o root -g root "$HERE/cleanup-out.sh" /usr/local/sbin/hapoalim-cleanup-out
install -m 0755 -o root -g root "$HERE/hapoalim-archive-import" /usr/local/sbin/hapoalim-archive-import
install -m 0755 -o root -g root "$HERE/hapoalim-archive-repair" /usr/local/sbin/hapoalim-archive-repair

# Image: built from the reviewed checkout, then pinned BY ID.
docker build --pull -t "$TAG" "$HERE/.."
image_id=$(docker image inspect --format '{{.Id}}' "$TAG")
printf 'HAPOALIM_SYNC_IMAGE=%s\n' "$image_id" >/etc/hapoalim/image.env
chmod 0644 /etc/hapoalim/image.env
docker run --rm --network none --entrypoint node "$image_id" -e \
  "const s=require('fs').readFileSync('/app/node_modules/israeli-bank-scrapers/lib/scrapers/hapoalim.js','utf8');if(!s.includes('LOCAL PATCH')||!s.includes('hapoalimWalkTransactions'))process.exit(3)" \
  || { echo "image is NOT patched" >&2; exit 1; }

install -m 0644 "$HERE/hapoalim-run.service" "$HERE/hapoalim-run.path" /etc/systemd/system/
# Drop-in: ReadWritePaths derived from the configured OUT_DIR / INBOX_DB (overrides/extends the
# defaults in the unit). Safe to re-run. If Ben previously added a manual drop-in for the same
# paths, remove it after this install to avoid confusion (systemd merges ReadWritePaths; no hard
# conflict, but two sources of truth is worse).
install -d -m 0755 /etc/systemd/system/hapoalim-run.service.d
cat > /etc/systemd/system/hapoalim-run.service.d/paths.conf <<PATHS_EOF
# Generated by setup-host.sh — do not edit by hand; re-run setup-host.sh after changing paths.
[Service]
ReadWritePaths=$DATA_DIR $INBOX_DIR
PATHS_EOF
chmod 0644 /etc/systemd/system/hapoalim-run.service.d/paths.conf
systemctl daemon-reload
systemctl enable --now hapoalim-run.path
echo "OK. Next: sudo hapoalim-setup  (type the bank credentials), then:"
echo "  # optional backfill from existing out/ CSVs (idempotent; coverage = row min..max + warning)"
echo "  sudo hapoalim-archive-import $OUT_DIR/hapoalim-*.csv 2>/dev/null || true"
echo "  cd ~/smarthome/home-agent && docker compose up -d --build command-center command-center-mcp && docker compose restart hermes"
echo "If you added a manual drop-in for ReadWritePaths earlier, remove it now (ours is paths.conf) and daemon-reload."
